#!/usr/bin/env python3
"""Generate docs/reference.md from the code: the run.py parser, config.SCHEMA, the event registry and the tables of
reference_data.py.

    gen_reference.py           write docs/reference.md
    gen_reference.py --check   exit 1 when docs/reference.md differs from what the code says

Never edit docs/reference.md by hand. Change the code (a help string, config.DESCRIPTIONS, events.EVENTS,
reference_data.py) and run this script again. Standard library only; Python 3.11 or later, found through
python-path.sh when the interpreter that started it is older.
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

if sys.version_info < (3, 11):
    found = subprocess.run([os.path.join(HERE, "python-path.sh")], capture_output=True, text=True)
    if found.returncode != 0:
        sys.exit(found.stderr.strip() or "gen_reference.py: no Python 3.11 or later found")
    os.execv(found.stdout.strip(), [found.stdout.strip(), os.path.abspath(__file__), *sys.argv[1:]])

import argparse  # noqa: E402
import json  # noqa: E402

sys.path.insert(0, HERE)
import config  # noqa: E402
import events  # noqa: E402
import reference_data as data  # noqa: E402
import run  # noqa: E402

PLUGIN_ROOT = os.path.dirname(HERE)
OUTPUT = os.path.join(PLUGIN_ROOT, "docs", "reference.md")
HEADER = ("<!-- Generated by scripts/gen_reference.py from the code. Do not edit: change the code or "
          "scripts/reference_data.py, then run scripts/gen_reference.py. -->\n")


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def plain(text):
    """Help text of the parser is not Markdown: keep <id> from reading as an HTML tag."""
    return text.replace("<", "\\<").replace(">", "\\>")


def sentence(text, more):
    return more if not text else (text if text.endswith(".") else text + ".") + " " + more


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def toml_default(kind, default):
    if callable(default):
        return "the system time zone, else `UTC`"
    if default is None:
        return "unset"
    if isinstance(default, bool):
        return f"`{str(default).lower()}`"
    if isinstance(default, dict) and "model" in default:
        if default.get("effort") is None:
            return f'`"{default["model"]}"`'
        return f'`{{ model = "{default["model"]}", effort = "{default["effort"]}" }}`'
    if isinstance(default, (list, dict)):
        return "`" + (json.dumps(default) if default else ("[]" if isinstance(default, list) else "{}")) + "`"
    return f"`{json.dumps(default)}`"


def config_section():
    out = ["## Configuration", "", data.CONFIG_INTRO, "",
           f"The config has {len(config.SCHEMA)} sections and {len(config.ALL_KEYS)} keys."]
    for section, keys in config.SCHEMA.items():
        out += ["", f"### `[{section}]`", ""]
        if section in config.SECTION_NOTES:
            out += [config.SECTION_NOTES[section], ""]
        rows = []
        for key, (kind, default) in keys.items():
            rows.append((f"`{key}`", config.type_name(kind), toml_default(kind, default),
                         config.DESCRIPTIONS[section][key]))
        out.append(table(["Key", "Type", "Default", "Meaning"], rows))
    return "\n".join(out)


def subcommands(parser):
    action = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {a.dest: a.help for a in action._choices_actions}
    return [(name, sub, helps.get(name) or "") for name, sub in action.choices.items()]


def argument_name(action):
    name = action.metavar if isinstance(action.metavar, str) else action.dest.upper()
    if action.nargs in ("+", "*"):
        return f"{name} [{name} ...]"
    return name


def option_default(action):
    default = action.default
    if default in (None, False, [], "", argparse.SUPPRESS):
        return ""
    return f"`{default}`"


def option_rows(sub):
    rows = []
    for action in sub._actions:
        if action.help == argparse.SUPPRESS or isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if action.option_strings:
            flags = ", ".join(f"`{s}`" for s in action.option_strings)
            argument = "" if action.nargs == 0 else argument_name(action)
        else:
            flags = f"`{argument_name(action)}`"
            argument = "optional" if action.nargs == "?" else ""
        meaning = plain(action.help or "")
        if action.choices and not isinstance(action.choices, dict):
            meaning = sentence(meaning, "One of " + ", ".join(f"`{c}`" for c in action.choices) + ".")
        if action.required and action.option_strings:
            meaning = sentence(meaning, "Required.")
        rows.append((flags, f"`{argument}`" if argument and argument != "optional" else argument, option_default(action), meaning))
    return rows


def usage(name, sub):
    parts = [f"run.py {name}"]
    for action in sub._actions:
        if action.help == argparse.SUPPRESS or isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if action.option_strings:
            flag = action.option_strings[0] + ("" if action.nargs == 0 else " " + argument_name(action))
            parts.append(flag if action.required else f"[{flag}]")
        else:
            parts.append(f"[{argument_name(action)}]" if action.nargs == "?" else argument_name(action))
    return " ".join(parts)


def run_section():
    parser = run.build_parser()
    commands = subcommands(parser)
    missing = [n for n, _, _ in commands if n not in data.COMMAND_DOCS]
    if missing:
        raise SystemExit(f"gen_reference.py: no COMMAND_DOCS entry for {', '.join(missing)}")
    out = ["## `run.py`", "", data.RUN_INTRO, "", "### Global options", ""]
    out.append(table(["Option", "Argument", "Default", "Meaning"], option_rows(parser)))
    out += ["", "### Commands", "", "| Command | What it does |", "|---|---|"]
    out += [f"| [`{n}`](#runpy-{n}) | {cell(plain(h))} |" for n, _, h in commands]
    for name, sub, _ in commands:
        out += ["", f"#### `run.py {name}`", "", "```text", usage(name, sub), "```", "", data.COMMAND_DOCS[name]]
        rows = option_rows(sub)
        if rows:
            out += ["", table(["Option", "Argument", "Default", "Meaning"], rows)]
    out += ["", "### Output and exit codes", "", data.RUN_OUTPUT, "", table(["Exit code", "Meaning"], data.EXIT_CODES)]
    out += ["", "### Events", "",
            f"`run.py` prints {len(events.EVENTS)} events. A name that is not in `scripts/events.py` is refused.", "",
            table(["Event", "Meaning"], [(f"`{n}`", d) for n, d in events.EVENTS.items()])]
    out += ["", "### Fixed values", "", table(["Name", "Values"], [
        ("Verdict levels (`close --verdict`)", ", ".join(f"`{v}`" for v in run.VERDICTS)),
        ("Launch causes (`launch --cause`)", ", ".join(f"`{v}`" for v in run.LAUNCH_CAUSES)),
        ("Abandon reasons", ", ".join(f"`{v}`" for v in run.ABANDON_MODES)),
        ("Round kinds", ", ".join(f"`{v}`" for v in sorted(run.ROUND_KINDS))),
        ("Dependency check verdicts", ", ".join(f"`{v}`" for v in run.DEPCHECK_VERDICTS)),
        ("Phases", ", ".join(f"`{v}`" for v in run.PHASES)),
        ("Verify kinds", ", ".join(f"`{v}`" for v in config.VERIFY_KINDS)),
        ("Model tiers", ", ".join(f"`{v}`" for v in config.TIERS)),
        ("Notification events", ", ".join(f"`{v}`" for v in config.NOTIFY_EVENTS)
         + "; also `" + "`, `".join(config.NOTIFY_OPTIONAL) + "` when listed in `notifications.events`"),
        ("Adjacent change kinds (`[scope] adjacent`)", ", ".join(f"`{v}`" for v in config.ADJACENT_KINDS)),
    ])]
    return "\n".join(out)


def meta_class(keys):
    classes = {next((c for c, listed in config.RUNTIME_META.items() if k in listed), "on the issue") for k in keys}
    if len(classes) != 1:
        raise SystemExit(f"gen_reference.py: the keys {keys} are not in one class: {sorted(classes)}")
    return classes.pop()


def key_list(keys):
    return ", ".join(f"`{k}`" for k in keys)


def meta_section():
    listed = {k for keys, _ in data.META_WHY for k in keys}
    unlisted = sorted(set(sum(config.RUNTIME_META.values(), ())) - listed)
    if unlisted:
        raise SystemExit(f"gen_reference.py: RUNTIME_META keys with no META_WHY row: {', '.join(unlisted)}")
    count = len({k for keys, _, _ in data.META_KEYS for k in keys})
    out = ["## Task metadata", "", data.META_INTRO + f" There are {count} keys.", "",
           table(["Key", "Set by", "Meaning"], [(key_list(keys), by, text) for keys, by, text in data.META_KEYS]),
           "", data.META_NOTES, "", "### Meta keys on the Taskgraph GitHub backend", "", data.META_CLASS_INTRO, "",
           table(["Key", "Class", "Why"], [(key_list(keys), meta_class(keys), why) for keys, why in data.META_WHY]),
           "", data.META_CLASS_NOTES, "", "The block to add to `.taskgraph.toml`. Put it in place before `run.py` first writes "
           "on the GitHub backend; `config.py check` warns about a key or kind that the project's entry does not list.",
           "", "```toml", '[projects."<name>".meta]']
    out += [f"{cls} = {json.dumps(list(keys))}" for cls, keys in config.RUNTIME_META.items()]
    out += ["", '[projects."<name>".results]', f"local = {json.dumps(list(config.LOCAL_RESULT_KINDS))}", "```",
            "", "Why `revise` stays off the `results` list, and what a lost cache costs, is in "
            "[GitHub backend](github-backend.md#result-kinds-on-the-taskgraph-github-backend)."]
    return "\n".join(out)


def results_section():
    return "\n".join(["## Results", "", data.RESULTS_INTRO, "",
                      table(["Kind", "Status", "Written by", "Meaning"], data.RESULT_KINDS), "", data.RESULTS_NOTES])


def render():
    parts = [HEADER, "# Reference", "",
             "Commands, configuration keys, events, task metadata and result kinds of agentic-team. Every table is "
             "generated from the code. For the quickstart see the [README](../README.md); for how the parts work see "
             "[Lifecycle](lifecycle.md).", "",
             "- [`run.py`](#runpy): commands, options, events, exit codes",
             "- [Configuration](#configuration): every key of `.agentic-team.toml`",
             "- [Task metadata](#task-metadata): the `meta` keys of a task and their class on the GitHub backend",
             "- [Results](#results): the result kinds and their statuses", "",
             run_section(), "", config_section(), "", meta_section(), "", results_section()]
    return "\n".join(parts) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate docs/reference.md from the code.")
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/reference.md is out of date; write nothing")
    opts = parser.parse_args(argv)
    text = render()
    if opts.check:
        try:
            with open(OUTPUT, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            print("docs/reference.md is out of date: run plugins/agentic-team/scripts/gen_reference.py and commit it",
                  file=sys.stderr)
            return 1
        print("ok    docs/reference.md is up to date")
        return 0
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
